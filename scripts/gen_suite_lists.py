#!/usr/bin/env python3
"""Generate assets/suite-apps.txt, the suite script's app list (WMINST-001).

The app sets are defined once: packaging/desktop.toml and packaging/extras.toml
(Debian names, the debs' Recommends), packaging/os-names.toml (how to find each
on Fedora, Arch and Homebrew) and packaging/script-only.toml (apps no distro
packages). This writes one line per package:

    size:group:check:apt:dnf:pacman:brew

and one per script-only app:

    size:script:name

size is desktop or extras (a size installs its own lines and the smaller
sizes' lines); group is apps, gui (only with a desktop session) or services
(the separate, default-no question). An empty name means "not on that system".

    python3 scripts/gen_suite_lists.py           write assets/suite-apps.txt
    python3 scripts/gen_suite_lists.py --check   exit 1 if it is out of date
"""
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PKG = ROOT / "packaging"
OUT = ROOT / "assets" / "suite-apps.txt"
SIZES = (("desktop", PKG / "desktop.toml"), ("extras", PKG / "extras.toml"))
MANAGERS = ("dnf", "pacman", "brew")
HEADER = ("# Generated by scripts/gen_suite_lists.py from packaging/*.toml. Do not edit.\n"
          "# size:group:check:apt:dnf:pacman:brew, or size:script:name\n")


# Entries of the suite script's former hand-written lists (EXTRAS, EXTRAS_GUI,
# SERVICES, OWN_APPS) that are deliberately not in the generated list, with why.
DROPPED = {
    "btop": "USER review 2026-10-31: a Suggests; tetron-wm does not call it by default (Activity is built in)",
}


class GenError(Exception):
    pass


def debian_name(rel: str) -> str:
    """The first alternative's package name: "7zip | p7zip-full" -> "7zip"."""
    return rel.split("|")[0].split("(")[0].strip()


def load(path: Path) -> dict:
    return tomllib.loads(path.read_text())


def generate(sizes=SIZES, os_names: Path = PKG / "os-names.toml", script_only: Path = PKG / "script-only.toml") -> str:
    names = load(os_names).get("app", {})
    used: set[str] = set()
    lines: list[str] = []

    def line(size: str, name: str, entry: dict, apt: str) -> str:
        if not entry.get("check"):
            raise GenError(f"os-names.toml: {name} has no check")
        if any(":" in v for v in [entry["check"], apt] + [entry.get(m, name) for m in MANAGERS]):
            raise GenError(f"os-names.toml: {name}: ':' is the field separator")
        group = entry.get("group", "apps")
        return ":".join([size, group, entry["check"], apt] + [entry.get(m, name) for m in MANAGERS])

    for size, toml in sizes:
        d = load(toml)
        for rel in d.get("recommends", []):
            n = debian_name(rel)
            if n not in names:
                raise GenError(f"{toml.name}: recommends {n} has no [app.{n}] in os-names.toml")
            used.add(n)
            lines.append(line(size, n, names[n], n))
        for rel in d.get("suggests", []):
            n = debian_name(rel)
            if names.get(n, {}).get("group") == "services":
                used.add(n)
                lines.append(line(size, n, names[n], n))
    for n, entry in names.items():
        if n in used:
            continue
        if entry.get("apt") != "" or entry.get("size") not in {s for s, _ in sizes}:
            raise GenError(f"os-names.toml: [app.{n}] is in no package; give it size and apt = \"\" or remove it")
        lines.append(line(entry["size"], n, entry, ""))
    for n, entry in load(script_only).get("script", {}).items():
        if entry.get("size") not in {s for s, _ in sizes}:
            raise GenError(f"script-only.toml: {n} needs size desktop or extras")
        lines.append(f"{entry['size']}:script:{n}")
    return HEADER + "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    try:
        text = generate()
    except GenError as e:
        print(f"gen_suite_lists: {e}", file=sys.stderr)
        return 1
    if "--check" in argv:
        current = OUT.exists() and OUT.read_text() == text
        if not current:
            print("gen_suite_lists: assets/suite-apps.txt is out of date; run python3 scripts/gen_suite_lists.py",
                  file=sys.stderr)
        return 0 if current else 1
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({text.count(chr(10)) - 2} entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
